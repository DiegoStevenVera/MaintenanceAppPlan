/// Read-only version view. The PDF is generated by the backend and opened locally with PDFKit.
struct PDFPreviewView: View {
    @EnvironmentObject private var session: SessionStore
    let versionID: String

    @State private var detail: APIReportVersionDetail?
    @State private var pdfData: Data?
    @State private var pdfURL: URL?
    @State private var isLoading = true
    @State private var isGenerating = false
    @State private var isPreparingEmail = false
    @State private var isPresentingPDF = false
    @State private var mailDraft: ReportEmailDraft?
    @State private var errorMessage: String?
    @State private var selectedPreventiveSection = PreventiveVersionSection.general
    @State private var selectedCorrectiveSection = CorrectiveVersionSection.event

    private var reportService: ReportAPIService {
        ReportAPIService(
            baseURLString: UserDefaults.standard.string(forKey: "apiBaseURL") ?? ""
        )
    }

    var body: some View {
        ScrollView {
            LazyVStack(
                alignment: .leading,
                spacing: AppSpacing.md,
                pinnedViews: [.sectionHeaders]
            ) {
                if let detail {
                    if detail.reportKind == "PREVENTIVE" {
                        preventiveVersionTitleBar(detail)
                        preventiveVersionHeader(detail)
                        Section {
                            selectedPreventiveContent(detail)
                        } header: {
                            preventiveSectionSelector
                                .padding(.vertical, 4)
                                .background(.ultraThinMaterial)
                        }
                    } else if detail.reportKind == "CORRECTIVE" {
                        correctiveVersionTitleBar(detail)
                        correctiveVersionHeader(detail)
                        Section {
                            selectedCorrectiveContent(detail)
                        } header: {
                            correctiveSectionSelector
                                .padding(.vertical, 4)
                                .background(.ultraThinMaterial)
                        }
                    } else {
                        header(detail)
                        generalData(detail)
                        participants(detail)
                        evidence(detail)
                        calibrationContent(detail)
                        if detail.documentStatus == "FINALIZED" {
                            pdfActions(detail)
                        }
                    }
                } else if isLoading {
                    ProgressView("Cargando versión del reporte")
                        .frame(maxWidth: .infinity, minHeight: 260)
                }

                if let errorMessage {
                    Text(errorMessage)
                        .foregroundStyle(.red)
                        .frame(maxWidth: .infinity, alignment: .leading)
                }
            }
            .padding(AppSpacing.lg)
            .frame(maxWidth: 1_420, alignment: .leading)
            .frame(maxWidth: .infinity)
        }
        .background(MaintenanceScreenBackground())
        .navigationTitle("Versión del reporte")
        .task { await loadDetail() }
        .sheet(isPresented: $isPresentingPDF) {
            if let pdfData {
                PDFDocumentViewer(data: pdfData)
            }
        }
        .sheet(item: $mailDraft) { draft in
            ReportMailComposer(draft: draft) { result in
                switch result {
                case .success(.sent):
                    errorMessage = "Correo preparado y enviado desde Mail."
                case .success:
                    break
                case .failure(let error):
                    errorMessage = error.localizedDescription
                }
            }
        }
    }

    private func correctiveVersionTitleBar(_ detail: APIReportVersionDetail) -> some View {
        ViewThatFits(in: .horizontal) {
            HStack(spacing: AppSpacing.lg) {
                Text("Versión del reporte correctivo")
                    .font(.title3.weight(.bold))
                    .fixedSize(horizontal: true, vertical: false)
                Spacer(minLength: AppSpacing.xl)
                if detail.documentStatus == "FINALIZED" {
                    preventiveVersionActions(detail)
                }
            }
            .frame(maxWidth: .infinity)

            VStack(alignment: .leading, spacing: AppSpacing.sm) {
                Text("Versión del reporte correctivo").font(.title3.weight(.bold))
                if detail.documentStatus == "FINALIZED" {
                    preventiveVersionActions(detail)
                        .frame(maxWidth: .infinity, alignment: .trailing)
                }
            }
            .frame(maxWidth: .infinity, alignment: .leading)
        }
        .padding(.vertical, AppSpacing.xs)
    }

    private func correctiveVersionHeader(_ detail: APIReportVersionDetail) -> some View {
        VStack(alignment: .leading, spacing: AppSpacing.sm) {
            Text(detail.activity.title)
                .font(.system(.largeTitle, design: .rounded).weight(.black))
            HStack(spacing: AppSpacing.sm) {
                Text("Versión \(detail.versionNumber)")
                    .font(.subheadline.weight(.semibold))
                Text(detail.documentStatus)
                    .font(.caption.weight(.bold))
                    .foregroundStyle(BrandColor.green)
                Text(detail.activity.subsystem).foregroundStyle(.secondary)
            }
            if let summary = detail.summary, !summary.isEmpty {
                Text(summary).foregroundStyle(.secondary)
            }
            Text("Lectura histórica: estos datos pertenecen a esta versión y no se editan desde aquí.")
                .font(.caption)
                .foregroundStyle(.secondary)
        }
        .padding(.bottom, AppSpacing.xs)
    }

    private var correctiveSectionSelector: some View {
        ScrollView(.horizontal, showsIndicators: false) {
            HStack(spacing: 0) {
                ForEach(Array(CorrectiveVersionSection.allCases.enumerated()), id: \.element.id) {
                    index, section in
                    Button {
                        withAnimation(.snappy) { selectedCorrectiveSection = section }
                    } label: {
                        HStack(spacing: AppSpacing.sm) {
                            Image(systemName: section.systemImage)
                            Text(String(index + 1))
                                .font(.caption.monospacedDigit())
                                .foregroundStyle(.secondary)
                            Text(section.title)
                                .font(.subheadline.weight(.semibold))
                                .lineLimit(1)
                        }
                        .foregroundStyle(selectedCorrectiveSection == section ? BrandColor.red : .primary)
                        .frame(minWidth: 185, minHeight: 48)
                        .padding(.horizontal, AppSpacing.sm)
                        .background(
                            selectedCorrectiveSection == section ? BrandColor.red.opacity(0.08) : Color.clear,
                            in: RoundedRectangle(cornerRadius: 8)
                        )
                        .overlay {
                            if selectedCorrectiveSection == section {
                                RoundedRectangle(cornerRadius: 8)
                                    .stroke(BrandColor.red.opacity(0.45), lineWidth: 1)
                            }
                        }
                    }
                    .buttonStyle(.plain)
                    .accessibilityLabel("Sección \(index + 1), \(section.title)")

                    if section != CorrectiveVersionSection.allCases.last {
                        Divider().frame(height: 26)
                    }
                }
            }
            .padding(4)
        }
        .background(.thinMaterial, in: RoundedRectangle(cornerRadius: 10))
        .overlay {
            RoundedRectangle(cornerRadius: 10)
                .stroke(BrandColor.glassStroke, lineWidth: 1)
        }
        .sensoryFeedback(.selection, trigger: selectedCorrectiveSection)
    }

    @ViewBuilder
    private func selectedCorrectiveContent(_ detail: APIReportVersionDetail) -> some View {
        if let report = detail.correctiveReport {
            switch selectedCorrectiveSection {
            case .event:
                correctiveEvent(detail, report: report)
            case .failure:
                correctiveFailure(report)
            case .analysis:
                correctiveAnalysis(report)
            case .activities:
                correctiveActivities(report)
            case .validation:
                correctiveValidation(report)
            case .conclusions:
                correctiveConclusion(report)
            case .evidence:
                evidence(detail)
            case .participants:
                participants(detail)
            }
        }
    }

